// Prepares what the Framer build needs, from the same sources as the prototype:
//   1. framer-upload/      the images to upload, named <section>__<asset>.webp (largest size), git-ignored
//   2. docs/FRAMER_CONTENT.md  every text and value to enter in the Framer property controls
// Usage: node tools/framer-pack.mjs
import fs from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const gen = JSON.parse(fs.readFileSync(path.join(root, 'assets/manifests/generated.json'), 'utf8')).assets;

// Load the page's content modules (TypeScript) as plain data.
const out = path.join(root, 'node_modules/.cache/framer-pack.mjs');
fs.mkdirSync(path.dirname(out), { recursive: true });
await build({
  stdin: { contents: "export * from './prototype/osp/content.ts'; export { DEEP_DIVES, DEEP_NOTES } from './prototype/gallery/content.ts';", resolveDir: root, loader: 'ts' },
  bundle: true, format: 'esm', platform: 'node', outfile: out, logLevel: 'error',
});
const C = await import(out + '?t=' + Date.now());

// The hero bubbles (prototype/osp/Hero.tsx) as data
const BUBBLES = [
  ['1', 'Your recording', 'Drop in one sound. It plays right away.', 'bub-recording'],
  ['2', 'LIFE', 'Every note performed a little differently.', 'dd-life'],
  ['3', 'SYNTH + IMPRINT', 'An oscillator coloured by your recording.', 'bub-synth'],
  ['4', 'REIMAGINED', 'Five modes, from faithful to far away.', 'dd-reimagined-mosaic'],
  ['5', 'SPACE', 'Four reverb engines.', 'dd-space'],
  ['6', 'Keyboard + arpeggiator', 'Chords, held notes and an arpeggiator for each layer.', 'dd-arp'],
];

// 1. Upload pack
const sections = {
  '01-hero': ['osp-hero-3l', ...BUBBLES.map((b) => b[3])],
  '02-first-note': C.CHAPTERS.map((c) => c.asset),
  '04-reimagined': C.MODES.map((m) => m.asset),
  '05-synth': C.SYNTH_STATES.map((s) => s.asset),
  '06-layers': [...C.LAYERS.map((l) => l.asset), 'gran-card'],
  '07-details': C.DETAILS.map((d) => d.asset),
  '08-features': C.ESSENTIALS.map((e) => e.asset),
  '20-deep-dives': [...new Set(C.DEEP_DIVES.flatMap((d) => d.views.map((v) => v.asset)))],
};
const upDir = path.join(root, 'framer-upload');
fs.rmSync(upDir, { recursive: true, force: true });
fs.mkdirSync(upDir);
const uploadRows = [];
for (const [sec, ids] of Object.entries(sections)) {
  for (const id of [...new Set(ids)]) {
    const a = gen[id];
    if (!a) { console.error(`MISSING asset ${id} (${sec})`); process.exitCode = 1; continue; }
    const f = a.files.webp[a.files.webp.length - 1];
    const name = `${sec}__${id}.webp`;
    fs.copyFileSync(path.join(root, 'assets/optimized', f.file), path.join(upDir, name));
    uploadRows.push(`| \`${name}\` | ${f.width}×${f.height} | ${a.alt.replace(/\|/g, '/')} |`);
  }
}

// 2. Content appendix
const esc = (s = '') => String(s).replace(/\|/g, '/').replace(/\n/g, ' ');
const md = [];
md.push('# Framer content appendix', '', 'Generated by `node tools/framer-pack.mjs` from `prototype/osp/content.ts` and `prototype/gallery/content.ts`.',
  'Every value to type into a Framer property control, in the order the controls appear. Do not edit by hand: change the content files and re-run.', '');
md.push('## Images to upload (`framer-upload/`)', '', 'Alt text is ready to paste into each image\'s alt field.', '', '| File | Size | Alt text |', '|---|---|---|', ...uploadRows, '');
md.push('## Hero · AnnotatedInstrument', '', 'Capture: `01-hero__osp-hero-3l.webp`. Editor W 1448, Editor H 1086. Markers after 1500 ms.', '', '| # | Label | X | Y | Wire "Marker n" to |', '|---|---|---|---|---|',
  ...C.DEEP_NOTES.map((n) => `| ${n.n} | ${n.title} | ${n.x} | ${n.y} | Open overlay **DD ${n.title}** |`), '');
md.push('## Hero · bubbles (native Bubble component)', '', '| # | Title | Line | Image |', '|---|---|---|---|', ...BUBBLES.map((b) => `| ${b[0]} | ${b[1]} | ${b[2]} | \`01-hero__${b[3]}.webp\` |`), '');
md.push('## DeepDive · Features (one list, used by all six overlays)', '');
for (const d of C.DEEP_DIVES) {
  md.push(`### ${d.n} · ${d.title}  (id \`${d.id}\`, media ${d.media})`, '', `- Kicker: ${d.kicker}`, `- Body: ${d.body}`, `- Facts: ${(d.facts ?? []).join(' · ') || '—'}`);
  d.views.forEach((v, i) => md.push(`- View ${i + 1}: **${v.label}** · image \`20-deep-dives__${v.asset}.webp\`${v.text ? ` · text: ${v.text}` : ''}`));
  md.push('');
}
md.push('Overlay "Start at (id)" per overlay: ' + C.DEEP_DIVES.map((d) => `\`${d.id}\``).join(', ') + '.', '');
md.push('## First Note · chapters (native)', '', '| # | Kicker | Title | Body | Image |', '|---|---|---|---|---|', ...C.CHAPTERS.map((c) => `| ${c.n} | ${c.kicker} | ${esc(c.title)} | ${esc(c.body)} | \`02-first-note__${c.asset}.webp\` |`), '', 'Each chapter also shows the pending line "Sound example in preparation".', '');
md.push('## Sounds · SoundDeck', '', 'Start at: 2 (the nyckelharpa). Files stay empty until the recordings exist.', '', '| Name | Line |', '|---|---|', ...C.DEMOS.map((d) => `| ${d.name} | ${esc(d.line)} |`), '');
md.push('## REIMAGINED · ViewSwitcher', '', 'Layout Side · Selector List · Text under Picture · Theme Light · Plate on · Max width 520 · Start at 3 (Mosaic) · A11y label "REIMAGINED mode" · Pending "Sound example in preparation".', '', '| Label | Hint | Image | Text |', '|---|---|---|---|', ...C.MODES.map((m) => `| ${m.label} | ${esc(m.hint)} | \`04-reimagined__${m.asset}.webp\` | **${m.label}.** ${esc(m.text)} |`), '');
md.push('## SYNTH + IMPRINT · ViewSwitcher', '', 'Layout Side · Selector Pills · Text under Selector · Theme Dark · Plate off · Start at 2 (Imprint) · A11y label "SYNTH state" · Caption "The SYNTH page of layer A, as it looks in OSP" · Pending "IMPRINT is new. Listening examples arrive with the first recordings."', '', '| Label | Image | Text |', '|---|---|---|', ...C.SYNTH_STATES.map((s) => `| ${s.label} | \`05-synth__${s.asset}.webp\` | ${esc(s.text)} |`), '');
md.push('## Layers · ViewSwitcher', '', 'Layout Stacked · Selector Pills · Text under Selector · Plate off · Start at 2 (Three) · A11y label "Number of layers".', '', '| Label | Image | Text |', '|---|---|---|', ...C.LAYERS.map((l) => `| ${l.label} | \`06-layers__${l.asset}.webp\` | ${esc(l.text)} Each layer has its own mode, REIMAGINED, EQ, SYNTH and arpeggiator lane. |`), '');
md.push('## Details · bento (native)', '', '| Tile | Image | Caption title | Caption |', '|---|---|---|---|', ...C.DETAILS.map((d) => `| ${d.id} | \`07-details__${d.asset}.webp\` | ${d.title} | ${esc(d.note)} |`), '');
md.push('## Deeper features (native)', '', ...C.ESSENTIALS.map((e) => `- **${e.kicker}**: ${e.title} ${e.body} Image \`08-features__${e.asset}.webp\``), '', '| Title | Text |', '|---|---|', ...C.DEEPER.map(([t, d]) => `| ${t} | ${esc(d)} |`), '');
md.push('## Technical (native)', '', '| Label | Value |', '|---|---|', ...C.SPECS.map(([k, v]) => `| ${k} | ${esc(v)} |`), '');
md.push('## FAQ', '', ...C.FAQ.flatMap((f) => [`**${f.q}**`, '', f.a, '']));
fs.writeFileSync(path.join(root, 'docs/FRAMER_CONTENT.md'), md.join('\n'));
console.log(`framer-upload/: ${uploadRows.length} images · docs/FRAMER_CONTENT.md written`);
