"""The reference corpus: generate the audio and manifests, validate them, summarise them (P0)."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from . import SAMPLE_RATE, __version__
from .audio import read_audio, sha256_file, stats, write_audio
from .fixtures.corpus_def import Fixture, fixtures
from .fixtures.synth import render_note, sympathetic
from .transcription.events import NoteEvent, midi_to_hz, note_name
from .visualization.plots import spectrogram_with_notes

LAB = Path(__file__).resolve().parents[1]
MANIFESTS = LAB / "fixtures" / "manifests"
OUTPUT = LAB / "output"
MANIFEST_SCHEMA = "osp-poly.fixture/1"
SEED = 20261109
LICENSE = "Generated by the lab's synthesiser (polyphonic_lab/fixtures/synth.py) in this repository; no third-party audio."


def sound_end(stem: np.ndarray, sr: int, floor_db: float = -60.0) -> float:
    """Where a stem has fallen `floor_db` below its peak for good (its audible end)."""
    peak = np.max(np.abs(stem))
    if peak <= 0:
        return 0.0
    above = np.nonzero(np.abs(stem) > peak * 10 ** (floor_db / 20))[0]
    return float(above[-1] / sr) if len(above) else 0.0


def render_fixture(fx: Fixture, sr: int = SAMPLE_RATE) -> tuple[np.ndarray, list[np.ndarray], np.ndarray | None]:
    stems = [render_note(p, fx.duration, sr, SEED + i, fx.pedal) for i, p in enumerate(fx.notes)]
    residual = sympathetic(fx.notes, fx.duration, sr) if fx.pedal else None
    mix = np.sum(stems, axis=0) + (residual if residual is not None else 0.0)
    return mix, stems, residual


def generate(audio_root: Path = OUTPUT, manifests: Path = MANIFESTS, only: list[str] | None = None) -> list[Path]:
    """Renders every fixture's mixture and stems under audio_root/corpus and writes its manifest."""
    manifests.mkdir(parents=True, exist_ok=True)
    written = []
    index = []
    for fx in fixtures():
        if only and fx.id not in only:
            continue
        mix, stems, residual = render_fixture(fx)
        base = Path("corpus") / fx.id
        mix_path = write_audio(audio_root / base / "mix.wav", mix[None, :], SAMPLE_RATE)
        notes = []
        for i, (p, stem) in enumerate(zip(fx.notes, stems)):
            nid = f"note-{i + 1:04d}"
            rel = base / "stems" / f"{nid}_{note_name(p.midi)}.wav"
            write_audio(audio_root / rel, stem[None, :], SAMPLE_RATE)
            notes.append({
                "id": nid, "pitch_midi": p.midi, "pitch_hz": round(midi_to_hz(p.midi), 4), "name": note_name(p.midi),
                "onset_seconds": p.onset, "offset_seconds": p.offset, "sound_end_seconds": round(sound_end(stem, SAMPLE_RATE), 4),
                "velocity": p.velocity, "instrument": p.instrument,
                "stem": {"path": str(rel), "sha256": sha256_file(audio_root / rel)},
            })
        res = None
        if residual is not None:
            rel = base / "stems" / "residual-truth.wav"
            write_audio(audio_root / rel, residual[None, :], SAMPLE_RATE)
            res = {"path": str(rel), "sha256": sha256_file(audio_root / rel), "what": "sympathetic resonance (pedal): never a note"}
        manifest = {
            "schema": MANIFEST_SCHEMA,
            "id": fx.id, "class": fx.cls, "family": fx.family, "complexity": fx.complexity, "description": fx.description,
            "input": {"path": str(base / "mix.wav"), "sha256": sha256_file(mix_path), "sampleRate": SAMPLE_RATE, "channels": 1,
                      "frames": int(len(mix)), "durationSeconds": fx.duration},
            "groundTruth": {"notes": notes, "residualStem": res, "pedal": fx.pedal,
                            "offsetMeaning": "offset_seconds is the key release; sound_end_seconds where the stem falls 60 dB below its peak"},
            "expectedFailures": fx.expected_failures,
            "provenance": {"license": LICENSE, "generator": "polyphonic_lab.fixtures.synth", "labVersion": __version__, "seed": SEED},
        }
        path = manifests / f"{fx.id}.json"
        path.write_text(json.dumps(manifest, indent=1) + "\n")
        written.append(path)
        index.append({"id": fx.id, "manifest": path.name, "class": fx.cls, "family": fx.family})
    if not only:
        (manifests / "corpus.json").write_text(json.dumps({"schema": "osp-poly.corpus/1", "fixtures": index}, indent=1) + "\n")
    return written


def load_manifest(path: Path) -> dict:
    m = json.loads(Path(path).read_text())
    if m.get("schema") != MANIFEST_SCHEMA:
        raise ValueError(f"{path}: not a {MANIFEST_SCHEMA} manifest")
    return m


def manifest_paths(index_or_manifest: Path) -> list[Path]:
    p = Path(index_or_manifest)
    doc = json.loads(p.read_text())
    if doc.get("schema") == "osp-poly.corpus/1":
        return [p.parent / f["manifest"] for f in doc["fixtures"]]
    return [p]


def truth_events(manifest: dict) -> list[NoteEvent]:
    return [NoteEvent(id=n["id"], pitch_midi=n["pitch_midi"], onset_seconds=n["onset_seconds"],
                      offset_seconds=n["offset_seconds"], velocity_estimate=n["velocity"], confidence=1.0,
                      source_id=n["instrument"], detector="ground-truth", status="accepted",
                      extra={"sound_end_seconds": n["sound_end_seconds"], "stem": n["stem"]["path"]})
            for n in manifest["groundTruth"]["notes"]]


def validate(index: Path, audio_root: Path = OUTPUT, out: Path | None = None, plots: bool = True) -> tuple[bool, dict]:
    """Checks every fixture's audio against its manifest (hashes, format, stems summing to the
    mix) and writes a summary, spectrograms with the known notes and an evaluation manifest."""
    out = Path(out or audio_root / "corpus-report")
    out.mkdir(parents=True, exist_ok=True)
    rows, ok_all = [], True
    tasks = {"transcription": [], "extraction": []}
    for mpath in manifest_paths(index):
        m = load_manifest(mpath)
        errors, warnings = [], []
        mix_path = audio_root / m["input"]["path"]
        if not mix_path.exists():
            errors.append(f"missing audio {mix_path} (run: osp-poly corpus generate)")
            rows.append({"id": m["id"], "errors": errors, "warnings": warnings})
            ok_all = False
            continue
        if sha256_file(mix_path) != m["input"]["sha256"]:
            warnings.append("mix hash differs from the manifest (regenerated on another platform?): checked by content instead")
        audio, sr = read_audio(mix_path)
        if sr != m["input"]["sampleRate"] or audio.shape[1] != m["input"]["frames"]:
            errors.append(f"format: {sr} Hz x {audio.shape[1]} frames, manifest says {m['input']['sampleRate']} x {m['input']['frames']}")
        total = np.zeros(audio.shape[1])
        for n in m["groundTruth"]["notes"]:
            sp = audio_root / n["stem"]["path"]
            if not sp.exists():
                errors.append(f"missing stem {sp}")
                continue
            s, _ = read_audio(sp)
            total += s[0]
        res = m["groundTruth"].get("residualStem")
        if res:
            total += read_audio(audio_root / res["path"])[0][0]
        if not errors:
            err = float(np.max(np.abs(total - audio[0])))
            if err > 1e-5:
                errors.append(f"stems do not sum to the mix (max error {err:.2e})")
        s = stats(audio, sr)
        if not s["finite"]:
            errors.append("non-finite samples")
        if s["peakDbfs"] > -0.1:
            warnings.append(f"peak {s['peakDbfs']} dBFS: near clipping")
        truth = [{"pitch_hz": n["pitch_hz"], "onset": n["onset_seconds"], "offset": n["sound_end_seconds"], "label": n["name"]}
                 for n in m["groundTruth"]["notes"]]
        image = None
        if plots and not errors:
            image = spectrogram_with_notes(audio, sr, out / "images" / f"{m['id']}.png", f"{m['id']}: known notes (to their audible end)", truth=truth)
        maxpoly = _max_polyphony(m["groundTruth"]["notes"])
        rows.append({"id": m["id"], "class": m["class"], "family": m["family"], "notes": len(truth), "maxPolyphony": maxpoly,
                     "stats": s, "errors": errors, "warnings": warnings, "image": str(image.relative_to(out)) if image else None})
        ok_all = ok_all and not errors
        tasks["transcription"].append({"id": m["id"], "manifest": str(mpath), "input": str(mix_path)})
        tasks["extraction"].append({"id": m["id"], "manifest": str(mpath), "input": str(mix_path), "stems": True})
    summary = {"schema": "osp-poly.corpus-report/1", "ok": ok_all, "fixtures": rows}
    (out / "summary.json").write_text(json.dumps(summary, indent=1) + "\n")
    (out / "evaluation-manifest.json").write_text(json.dumps({"schema": "osp-poly.evaluation/1", "tasks": tasks}, indent=1) + "\n")
    (out / "summary.md").write_text(_summary_md(rows, ok_all))
    return ok_all, summary


def _max_polyphony(notes: list[dict]) -> int:
    edges = sorted([(n["onset_seconds"], 1) for n in notes] + [(n["sound_end_seconds"], -1) for n in notes])
    cur = best = 0
    for _, d in edges:
        cur += d
        best = max(best, cur)
    return best


def _summary_md(rows: list[dict], ok: bool) -> str:
    lines = ["# Reference corpus summary", "", f"**{'All fixtures valid' if ok else 'ERRORS: see below'}** ({len(rows)} fixtures)", "",
             "| Fixture | Class | Family | Notes | Max polyphony | Seconds | Peak dBFS | RMS dBFS | Issues |", "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        s = r.get("stats", {})
        issues = "; ".join(r["errors"] + r["warnings"]) or "-"
        lines.append(f"| {r['id']} | {r.get('class', '')} | {r.get('family', '')} | {r.get('notes', '')} | {r.get('maxPolyphony', '')} | "
                     f"{s.get('seconds', '')} | {s.get('peakDbfs', '')} | {s.get('rmsDbfs', '')} | {issues} |")
    lines += ["", "Images: `images/<fixture>.png` (spectrogram, known notes to their audible end)."]
    return "\n".join(lines) + "\n"
